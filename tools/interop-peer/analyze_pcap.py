#!/usr/bin/env python3
"""
Jinn OS — PCAP Forensic Traffic Analyzer
Decodes and verifies PCAP files generated by QEMU filter-dump to provide
indisputable evidence of TCP handshakes, multi-segment streaming, JinnWall drops,
and connection teardowns.
"""

import sys
import struct
import os

def parse_pcap(filepath):
    if not os.path.exists(filepath):
        print(f"PCAP file not found: {filepath}")
        return None

    with open(filepath, "rb") as f:
        data = f.read()

    if len(data) < 24:
        print("PCAP file too short for global header")
        return None

    magic = struct.unpack("<I", data[:4])[0]
    if magic == 0xA1B2C3D4:
        endian = "<"
    elif magic == 0xD4C3B2A1:
        endian = ">"
    else:
        print(f"Unknown PCAP magic: 0x{magic:08X}")
        return None

    _, ver_maj, ver_min, _, _, snaplen, network = struct.unpack(f"{endian}IHHiIII", data[:24])
    # network == 1 is LINKTYPE_ETHERNET

    offset = 24
    packets = []

    while offset + 16 <= len(data):
        ts_sec, ts_usec, incl_len, orig_len = struct.unpack(f"{endian}IIII", data[offset:offset+16])
        offset += 16
        if offset + incl_len > len(data):
            break
        pkt_data = data[offset:offset+incl_len]
        offset += incl_len

        # Parse Ethernet
        if len(pkt_data) < 14:
            continue
        ethertype = struct.unpack(">H", pkt_data[12:14])[0]
        if ethertype != 0x0800: # IPv4
            continue

        ip_data = pkt_data[14:]
        if len(ip_data) < 20:
            continue
        ihl = (ip_data[0] & 0x0F) * 4
        protocol = ip_data[9]
        src_ip = ".".join(str(b) for b in ip_data[12:16])
        dst_ip = ".".join(str(b) for b in ip_data[16:20])

        if protocol == 6: # TCP
            tcp_data = ip_data[ihl:]
            if len(tcp_data) < 20:
                continue
            src_port, dst_port, seq, ack, doff_flags, window = struct.unpack(">HHIIHH", tcp_data[:16])
            doff = ((doff_flags >> 12) & 0x0F) * 4
            flags = doff_flags & 0x3F

            flag_names = []
            if flags & 0x02: flag_names.append("SYN")
            if flags & 0x10: flag_names.append("ACK")
            if flags & 0x08: flag_names.append("PSH")
            if flags & 0x01: flag_names.append("FIN")
            if flags & 0x04: flag_names.append("RST")

            payload_len = len(tcp_data) - doff

            packets.append({
                "ts": ts_sec + ts_usec / 1_000_000.0,
                "src": f"{src_ip}:{src_port}",
                "dst": f"{dst_ip}:{dst_port}",
                "src_port": src_port,
                "dst_port": dst_port,
                "seq": seq,
                "ack": ack,
                "flags": "|".join(flag_names) if flag_names else "NONE",
                "window": window,
                "payload_len": payload_len,
            })

    return packets

def summarize_traffic(packets):
    if not packets:
        print("No TCP packets found in capture.")
        return

    print("==================================================================")
    print("  JINN OS PCAP FORENSIC TRAFFIC EVIDENCE SUMMARY")
    print("==================================================================")
    print(f"Total TCP Packets Captured: {len(packets)}\n")

    # Group by conversation / ports
    streams = {}
    for p in packets:
        pair = tuple(sorted([p["src_port"], p["dst_port"]]))
        if pair not in streams:
            streams[pair] = []
        streams[pair].append(p)

    print("--- Detected TCP Conversations ---")
    for pair, pkts in streams.items():
        syns = sum(1 for p in pkts if "SYN" in p["flags"])
        fins = sum(1 for p in pkts if "FIN" in p["flags"])
        rsts = sum(1 for p in pkts if "RST" in p["flags"])
        total_bytes = sum(p["payload_len"] for p in pkts)
        max_seg = max((p["payload_len"] for p in pkts), default=0)
        print(f"Stream ports {pair[0]} <-> {pair[1]}: {len(pkts)} packets, {total_bytes} payload bytes, MaxSeg={max_seg}B, SYNs={syns}, FINs={fins}, RSTs={rsts}")

    print("\n--- Key Forensic Milestones ---")
    
    # 1. Handshake with 9999
    conn_9999 = [p for p in packets if 9999 in (p["src_port"], p["dst_port"])]
    syn_9999 = [p for p in conn_9999 if p["flags"] == "SYN"]
    synack_9999 = [p for p in conn_9999 if "SYN" in p["flags"] and "ACK" in p["flags"]]
    if syn_9999 and synack_9999:
        print(f"  [EVIDENCE] 3-Way Handshake with Peer 9999: VERIFIED (SYN seq={syn_9999[0]['seq']} -> SYN-ACK ack={synack_9999[0]['ack']})")

    # 2. Multi-segment (> MSS) transfer
    large_segs = [p for p in conn_9999 if p["payload_len"] > 1400]
    if large_segs:
        print(f"  [EVIDENCE] Multi-Segment Transfer (> MSS): VERIFIED ({len(large_segs)} segments > 1400 bytes, e.g. {large_segs[0]['payload_len']} bytes)")

    # 3. Port 8080 (JinnWall PublicSecure block & Development allow)
    conn_8080 = [p for p in packets if 8080 in (p["src_port"], p["dst_port"])]
    syn_8080 = [p for p in conn_8080 if p["flags"] == "SYN"]
    synack_8080 = [p for p in conn_8080 if "SYN" in p["flags"] and "ACK" in p["flags"]]
    print(f"  [EVIDENCE] Inbound Traffic to Port 8080: Total {len(conn_8080)} packets. Inbound SYNs={len(syn_8080)}, SYN-ACKs={len(synack_8080)}")
    if len(syn_8080) > len(synack_8080):
        print(f"  [EVIDENCE] JinnWall Filtering Proven: Inbound SYN dropped without answer under PublicSecure policy.")
    if synack_8080:
        print(f"  [EVIDENCE] JinnWall Authorization Proven: Inbound SYN accepted with SYN-ACK under Development policy.")

    # 4. Port 9991 (Closed port RST)
    conn_9991 = [p for p in packets if 9991 in (p["src_port"], p["dst_port"])]
    rst_9991 = [p for p in conn_9991 if "RST" in p["flags"]]
    if rst_9991:
        print(f"  [EVIDENCE] Closed Port RST: VERIFIED (RST received on port 9991)")

    # 5. Graceful Teardown
    fin_pkts = [p for p in conn_9999 if "FIN" in p["flags"]]
    if fin_pkts:
        print(f"  [EVIDENCE] Graceful Connection Teardown: VERIFIED ({len(fin_pkts)} FIN packets exchanged)")

    print("==================================================================\n")

def main():
    filepath = sys.argv[1] if len(sys.argv) > 1 else "interop_capture.pcap"
    pkts = parse_pcap(filepath)
    if pkts is not None:
        summarize_traffic(pkts)

if __name__ == "__main__":
    main()
