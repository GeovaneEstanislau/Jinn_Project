//! Fonte Bitmap 8x8 e Primitivas de Texto para Janelas de Usuário (Ring 3)

pub const FONT_WIDTH: usize = 8;
pub const FONT_HEIGHT: usize = 8;

pub fn get_glyph(ch: u8) -> &'static [u8; 8] {
    if (32..=126).contains(&ch) {
        &FONT_8X8[(ch - 32) as usize]
    } else {
        &FONT_8X8[0] // fallback para espaço
    }
}

pub fn draw_char(
    buf: &mut [u32],
    w: usize,
    h: usize,
    ch: u8,
    x: usize,
    y: usize,
    fg: u32,
    bg: Option<u32>,
) {
    draw_char_clipped(buf, w, h, ch, x, y, fg, bg, 0, h);
}

pub fn draw_char_clipped(
    buf: &mut [u32],
    w: usize,
    h: usize,
    ch: u8,
    x: usize,
    y: usize,
    fg: u32,
    bg: Option<u32>,
    min_y: usize,
    max_y: usize,
) {
    if x >= w || y >= h {
        return;
    }
    let glyph = get_glyph(ch);
    let limit_y = (y + FONT_HEIGHT).min(h).min(max_y);
    let limit_x = (x + FONT_WIDTH).min(w);

    for (y_offset, row_byte) in glyph.iter().enumerate() {
        let cy = y + y_offset;
        if cy < min_y || cy >= limit_y {
            continue;
        }
        let row_ptr = cy * w;

        for x_offset in 0..8 {
            let cx = x + x_offset;
            if cx >= limit_x {
                break;
            }

            if (row_byte & (1 << (7 - x_offset))) != 0 {
                buf[row_ptr + cx] = fg;
            } else if let Some(bg_color) = bg {
                buf[row_ptr + cx] = bg_color;
            }
        }
    }
}

pub fn draw_text(
    buf: &mut [u32],
    w: usize,
    h: usize,
    mut x: usize,
    y: usize,
    text: &[u8],
    fg: u32,
    bg: Option<u32>,
) {
    for &ch in text {
        draw_char(buf, w, h, ch, x, y, fg, bg);
        x += FONT_WIDTH;
        if x >= w {
            break;
        }
    }
}

pub fn draw_text_clipped(
    buf: &mut [u32],
    w: usize,
    h: usize,
    mut x: usize,
    y: usize,
    text: &[u8],
    fg: u32,
    bg: Option<u32>,
    min_y: usize,
    max_y: usize,
) {
    for &ch in text {
        draw_char_clipped(buf, w, h, ch, x, y, fg, bg, min_y, max_y);
        x += FONT_WIDTH;
        if x >= w {
            break;
        }
    }
}

