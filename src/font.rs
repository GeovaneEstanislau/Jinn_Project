//! Embedded 8x8 ASCII Bitmap Font for Framebuffer Console
//!
//! Glyphs for ASCII characters 32 (' ') to 126 ('~').
//! Each glyph consists of 8 bytes (8 rows of 8 horizontal pixels).

pub const FONT_WIDTH: usize = 8;
pub const FONT_HEIGHT: usize = 8;

pub fn get_glyph(ch: u8) -> &'static [u8; 8] {
    let index = if ch >= 32 && ch <= 126 {
        (ch - 32) as usize
    } else {
        0 // fallback to space
    };
    &FONT_8X8[index]
}

